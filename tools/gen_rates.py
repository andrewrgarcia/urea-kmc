"""Generate src/rates_table.rs from data/piana_gale_2005_rates.json.

Run: uv run python tools/gen_rates.py
The JSON is the decoded Supplementary Information of Piana, Reyhani & Gale,
Nature 438, 70 (2005). Keys are "<in-plane>/<c-axis>", e.g. "12/B".
"""
import json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
d = json.loads((root / "data/piana_gale_2005_rates.json").read_text())
cols = ["-", "1", "11", "2", "12", "112", "22", "122", "1122"]
rows = ["-", "A", "B", "AB"]


def table(name):
    out = []
    for r in rows:
        line = []
        for c in cols:
            v = d[name][f"{c}/{r}"]
            if len(v) == 1:
                v = v * 3
            line.append("[" + ", ".join(f"{x:.4e}" for x in v) + "]")
        out.append("    [" + ", ".join(line) + "],")
    return "\n".join(out)


def split_mask():
    lines = []
    for r in rows:
        lines.append("    [" + ", ".join(
            "true" if len(d["water_dissolution"][f"{c}/{r}"]) == 3 else "false" for c in cols) + "],")
    return "\n".join(lines)


src = f"""// GENERATED by tools/gen_rates.py from data/piana_gale_2005_rates.json. Do not edit.
// Rates in s^-1, indexed [row][col][split].
// row: c-axis neighbors  0 "-", 1 "A", 2 "B", 3 "AB"
// col: in-plane neighbors 0 "-", 1 "1", 2 "11", 3 "2", 4 "12", 5 "112", 6 "22", 7 "122", 8 "1122"
// split: second-neighbor classes i, ii, iii (single-valued cells repeat the value).

pub type Table = [[[f64; 3]; 9]; 4];

pub const SPLIT: [[bool; 9]; 4] = [
{split_mask()}
];

pub const WATER_DISSOLUTION: Table = [
{table("water_dissolution")}
];

pub const WATER_CRYSTALLIZATION: Table = [
{table("water_crystallization")}
];

pub const METHANOL_DISSOLUTION: Table = [
{table("methanol_dissolution")}
];

pub const METHANOL_CRYSTALLIZATION: Table = [
{table("methanol_crystallization")}
];
"""
(root / "src/rates_table.rs").write_text(src)
print("wrote src/rates_table.rs")
